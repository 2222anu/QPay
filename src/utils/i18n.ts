// Global Translation Function
export function translate(text: string, lang: SupportedLanguage): string {
  if (!text || lang === 'English') return text;
  
  const trimmed = text.trim();
  if (DICTIONARY[trimmed] && DICTIONARY[trimmed][lang]) {
    return DICTIONARY[trimmed][lang];
  }

  // Check case-insensitive
  const foundKey = Object.keys(DICTIONARY).find(
    (k) => k.toLowerCase() === trimmed.toLowerCase()
  );
  if (foundKey && DICTIONARY[foundKey][lang]) {
    return DICTIONARY[foundKey][lang];
  }

  return text;
}

// In-Memory active language storage
let currentActiveLanguage: SupportedLanguage = 'English';

export function getAppLanguage(): SupportedLanguage {
  return currentActiveLanguage;
}

export function setGlobalLanguage(lang: SupportedLanguage): void {
  currentActiveLanguage = lang;
  try {
    localStorage.setItem('qtpay_lang', lang);
  } catch {
    // Ignore
  }
}
